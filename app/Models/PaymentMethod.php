<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Concerns\HasUuids;
use Illuminate\Database\Eloquent\Factories\HasFactory;

class PaymentMethod extends Model
{
    use HasFactory, HasUuids;

    /*
    |--------------------------------------------------------------------------
    | Fillable
    |--------------------------------------------------------------------------
    */

    protected $fillable = [

        /*
        |--------------------------------------------------------------------------
        | Informasi Payment Method
        |--------------------------------------------------------------------------
        */

        'name',
        'code',
        'category',

        /*
        |--------------------------------------------------------------------------
        | Provider / Gateway
        |--------------------------------------------------------------------------
        */

        'provider',

        /*
        |--------------------------------------------------------------------------
        | Manual Transfer
        |--------------------------------------------------------------------------
        */

        'account_number',
        'account_name',

        /*
        |--------------------------------------------------------------------------
        | Payment Fee
        |--------------------------------------------------------------------------
        */

        'fee_type',
        'fee_value',
        'fee_tax_type',

        /*
        |--------------------------------------------------------------------------
        | Media
        |--------------------------------------------------------------------------
        */

        'image_url',

        /*
        |--------------------------------------------------------------------------
        | Status
        |--------------------------------------------------------------------------
        */

        'status',

        /*
        |--------------------------------------------------------------------------
        | Metadata
        |--------------------------------------------------------------------------
        */

        'metadata',
    ];

    /*
    |--------------------------------------------------------------------------
    | Casts
    |--------------------------------------------------------------------------
    */

    protected function casts(): array
    {
        return [

            // Payment fee
            'fee_value' => 'decimal:2',

            // Metadata JSON
            'metadata' => 'array',
        ];
    }

    /*
    |--------------------------------------------------------------------------
    | Accessor
    |--------------------------------------------------------------------------
    */

    /*
    |--------------------------------------------------------------------------
    | URL logo payment method
    |--------------------------------------------------------------------------
    */

    public function getImageUrlAttribute($value): ?string
    {
        if (!$value) {
            return null;
        }

        // Jika sudah full URL
        if (
            str_starts_with($value, 'http://') ||
            str_starts_with($value, 'https://')
        ) {
            return $value;
        }

        return asset('storage/' . $value);
    }

    /*
    |--------------------------------------------------------------------------
    | Status Available
    |--------------------------------------------------------------------------
    */

    public function getIsAvailableAttribute(): bool
    {
        return $this->status === 'available';
    }

    /*
    |--------------------------------------------------------------------------
    | Scope
    |--------------------------------------------------------------------------
    */

    public function scopeAvailable($query)
    {
        return $query->where(
            'status',
            'available'
        );
    }

    /*
    |--------------------------------------------------------------------------
    | Hitung Payment Fee
    |--------------------------------------------------------------------------
    */

    public function calculateFee(int $amount): int
    {
        /*
        |--------------------------------------------------------------------------
        | Fixed Fee
        |--------------------------------------------------------------------------
        */

        if ($this->fee_type === 'fixed') {

            $fee = (float) $this->fee_value;

            /*
            |--------------------------------------------------------------------------
            | Fee sebelum pajak
            |--------------------------------------------------------------------------
            */

            if ($this->fee_tax_type === 'before_tax') {

                // Tambahkan PPN 11%
                $fee *= 1.11;
            }

            return (int) round($fee);
        }

        /*
        |--------------------------------------------------------------------------
        | Percent Fee
        |--------------------------------------------------------------------------
        */

        if ($this->fee_type === 'percent') {

            $fee = $amount * (
                ((float) $this->fee_value) / 100
            );

            return (int) round($fee);
        }

        return 0;
    }
}
